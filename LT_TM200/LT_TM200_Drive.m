function LT_TM200_Drive(Dir)

coder.extrinsic("write");

ltbus_device = ML_Get_Device_Port();

if Dir == -1 % DOWN | Compression
    write(ltbus_device, [0x7B 0x01 0xEA 0x0E 0xD0 0x02 0x00 0x1D 0x00 0x9E 0x66 0x7D], "uint8");
elseif Dir == 0
    write(ltbus_device, [0x7B 0x01 0xEA 0x0E 0xD0 0x02 0x00 0x00 0x00 0x77 0x43 0x7D], "uint8");
elseif Dir == 1 % UP | Tension
    write(ltbus_device, [0x7B 0x01 0xEA 0x0E 0xD0 0x02 0x00 0x1B 0x00 0x4E 0x32 0x7D], "uint8");
end

end
